/// A region of USBRAM allocated to a single endpoint/direction
///
/// Isochronous endpoints are always double-buffered, so `addr2` holds the second buffer's address for those
/// - the driver picks between `addr`/`addr2` on every transaction based on the current `DTOGTX`/`DTOGRX` bit
/// - see `Usbd::iso_in_next_buffer`/`iso_out_ready_buffer`
#[derive(Copy, Clone)]
struct EndpointBuffer {
    usbram_base: StaticRef<UsbRamRegisters>,
    addr: u16,
    addr2: Option<u16>,
    len: u16,
}
impl EndpointBuffer {
    /// Copies bytes from the given address in USBRAM into the given buffer
    fn read_at(
        &self,
        addr: u16,
        dest: &[InMemoryRegister<u8>],
        len: usize,
    ) -> Result<(), ErrorCode> {
        if len > self.len as usize || len > dest.len() {
            return Err(ErrorCode::SIZE);
        }

        // USBRAM is only word-addressable, so transfers are done 4 bytes at a time
        for i in 0..len.div_ceil(USBRAM_ALIGN) {
            let addr_as_words = addr as usize / USBRAM_ALIGN + i;

            // The address stored in endpoints is absolute; it includes those registers at the start of USBRAM
            // However, the `mem` field needs those words subtracted (2 per endpoint)
            let addr_as_words_corrected = addr_as_words
                .checked_sub(EP_COUNT * 2)
                .ok_or(ErrorCode::INVAL)?;

            let word = self
                .usbram_base
                .mem
                .get(addr_as_words_corrected)
                .ok_or(ErrorCode::INVAL)?;
            let bytes = word.get().to_le_bytes();

            let n = USBRAM_ALIGN.min(len - i * USBRAM_ALIGN);
            for j in 0..n {
                dest[i * USBRAM_ALIGN + j].set(bytes[j]);
            }
        }

        Ok(())
    }

    /// Copies bytes from the given buffer into the given address in USBRAM
    fn write_at(
        &self,
        addr: u16,
        src: &[InMemoryRegister<u8>],
        len: usize,
    ) -> Result<(), ErrorCode> {
        if len > self.len as usize || len > src.len() {
            return Err(ErrorCode::SIZE);
        }

        for i in 0..len.div_ceil(USBRAM_ALIGN) {
            let mut bytes = [0u8; USBRAM_ALIGN];
            let n = USBRAM_ALIGN.min(len - i * USBRAM_ALIGN);
            for j in 0..n {
                bytes[j] = src[i * USBRAM_ALIGN + j].get();
            }

            let addr_as_words = addr as usize / USBRAM_ALIGN + i;
            let addr_as_words_corrected = addr_as_words
                .checked_sub(EP_COUNT * 2)
                .ok_or(ErrorCode::INVAL)?;

            let word = self
                .usbram_base
                .mem
                .get(addr_as_words_corrected)
                .ok_or(ErrorCode::INVAL)?;
            word.set(u32::from_le_bytes(bytes));
        }

        Ok(())
    }

    /// Copies bytes from USBRAM into the given buffer, using the primary (or only) buffer address
    fn read(&self, dest: &[InMemoryRegister<u8>], len: usize) -> Result<(), ErrorCode> {
        self.read_at(self.addr, dest, len)
    }

    /// Copies bytes from the given buffer into USBRAM, using the primary (or only) buffer address
    fn write(&self, src: &[InMemoryRegister<u8>], len: usize) -> Result<(), ErrorCode> {
        self.write_at(self.addr, src, len)
    }
}

