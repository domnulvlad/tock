/// USB endpoint transfer type
///
/// The values of this enum can be directly cast into `u8` to get the transfer `bmAttributes` transfer type bits
#[derive(Clone, Copy, Eq, PartialEq)]
#[repr(u8)]
pub enum EndpointType {
    /// Control endpoint
    ///
    /// Used for device management
    ///
    /// Only the host can initiate requests
    ///
    /// Usually used only endpoint 0
    Control = 0b00,
    /// Isochronous endpoint
    ///
    /// Used for time-critical unreliable data
    Isochronous = 0b01,
    /// Bulk endpoint
    ///
    /// Used for large amounts of best-effort reliable data
    Bulk = 0b10,
    /// Interrupt endpoint
    ///
    /// Used for small amounts of time-critical reliable data
    Interrupt = 0b11,
}

/// Converts between the kernel's generic `TransferType` and the chip-level `EndpointType`
fn endpoint_type_from(t: TransferType) -> EndpointType {
    match t {
        TransferType::Control => EndpointType::Control,
        TransferType::Isochronous => EndpointType::Isochronous,
        TransferType::Bulk => EndpointType::Bulk,
        TransferType::Interrupt => EndpointType::Interrupt,
    }
}
/// Converts between the chip-level `EndpointType` and the kernel's generic `TransferType`
fn transfer_type_from(t: EndpointType) -> TransferType {
    match t {
        EndpointType::Control => TransferType::Control,
        EndpointType::Isochronous => TransferType::Isochronous,
        EndpointType::Bulk => TransferType::Bulk,
        EndpointType::Interrupt => TransferType::Interrupt,
    }
}

